"""Date- and shape-aware schedule fallback from the bundled GTFS timetable.

The timetable is package data generated by ``scripts/generate_timetable.py``.
Nothing here performs network I/O, so the fallback keeps working when every
STPT web service is down.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, date, datetime, timedelta
from datetime import time as time_type
from importlib.resources import files
from itertools import accumulate
from typing import Any
from zoneinfo import ZoneInfo

from stpt_mcp.config import Settings
from stpt_mcp.errors import ErrorCode, StptError
from stpt_mcp.models import Direction
from stpt_mcp.network import NetworkIndex, StopRecord
from stpt_mcp.providers.base import ProviderResult, ScheduleDeparture

_MINUTES_PER_DAY = 24 * 60


@dataclass(frozen=True, slots=True)
class ServiceCalendar:
    days: str  # seven "0"/"1" flags, Monday first, as in GTFS calendar.txt
    start: str
    end: str
    added: frozenset[str]
    removed: frozenset[str]

    def runs_on(self, day: date) -> bool:
        key = day.strftime("%Y%m%d")
        if key in self.removed:
            return False
        if key in self.added:
            return True
        return (
            bool(self.start) and self.start <= key <= self.end and self.days[day.weekday()] == "1"
        )


@dataclass(frozen=True, slots=True)
class TimetableTrip:
    service_id: str
    start_minute: int
    offsets: tuple[int, ...]  # minutes after the first stop, one per shape stop


@dataclass(frozen=True, slots=True)
class Timetable:
    generated_at: datetime
    feed_version: str
    start: date
    end: date
    services: dict[str, ServiceCalendar]
    trips: dict[str, tuple[TimetableTrip, ...]]


def _service_date(value: str) -> date:
    return datetime.strptime(value, "%Y%m%d").date()


def load_timetable(path: Any | None = None) -> Timetable:
    raw_path = path or (files("stpt_mcp.data") / "timetable.json")
    try:
        raw = json.loads(raw_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError("bundled timetable is missing or invalid") from exc
    if not isinstance(raw, dict) or raw.get("schema_version") != 1:
        raise RuntimeError("unsupported timetable schema")

    services = {
        str(service_id): ServiceCalendar(
            days=str(value["days"]),
            start=str(value["start"]),
            end=str(value["end"]),
            added=frozenset(str(day) for day in value["added"]),
            removed=frozenset(str(day) for day in value["removed"]),
        )
        for service_id, value in raw["services"].items()
    }
    trips: dict[str, tuple[TimetableTrip, ...]] = {}
    for shape_id, value in raw["shapes"].items():
        patterns = [
            (0, *accumulate(int(delta) for delta in deltas)) for deltas in value["patterns"]
        ]
        trips[str(shape_id)] = tuple(
            TimetableTrip(
                service_id=str(service_id),
                start_minute=int(start_minute),
                offsets=patterns[int(pattern)],
            )
            for service_id, start_minute, pattern in value["trips"]
        )
    return Timetable(
        generated_at=datetime.fromisoformat(str(raw["generated_at"]).replace("Z", "+00:00")),
        feed_version=str(raw.get("feed_version", "unknown")),
        start=_service_date(str(raw["service_range"]["start"])),
        end=_service_date(str(raw["service_range"]["end"])),
        services=services,
        trips=trips,
    )


class ScheduleProvider:
    def __init__(
        self,
        settings: Settings,
        network: NetworkIndex,
        timetable: Timetable | None = None,
    ) -> None:
        self._network = network
        self._zone = ZoneInfo(settings.timezone)
        self._timetable = timetable or load_timetable()

    @property
    def timetable(self) -> Timetable:
        return self._timetable

    async def fetch_stop_schedule(
        self,
        stop: StopRecord,
        service_date: date,
    ) -> ProviderResult[tuple[ScheduleDeparture, ...]]:
        """Return departures from ``stop`` around ``service_date``.

        Trips of the previous service day run past midnight (GTFS times above
        24:00) and next-day trips fall inside long lookahead windows, so three
        service days are expanded. The caller filters by the request instant.
        """
        timetable = self._timetable
        # The day after the last service day still has that day's after-midnight trips.
        if not timetable.start <= service_date <= timetable.end + timedelta(days=1):
            raise StptError(
                ErrorCode.SCHEDULE_UNAVAILABLE,
                f"The bundled timetable covers {timetable.start.isoformat()} to "
                f"{timetable.end.isoformat()} and has no service for {service_date.isoformat()}.",
                retryable=False,
                upstream="schedule",
            )
        if not stop.shapes:
            raise StptError(
                ErrorCode.SCHEDULE_UNAVAILABLE,
                f"No schedule shapes are known for stop {stop.stop_id}.",
                retryable=False,
                upstream="schedule",
            )

        departures: list[ScheduleDeparture] = []
        seen: set[tuple[str, Direction, datetime]] = set()
        for day in (
            service_date - timedelta(days=1),
            service_date,
            service_date + timedelta(days=1),
        ):
            active = {
                service_id
                for service_id, calendar in timetable.services.items()
                if calendar.runs_on(day)
            }
            for shape_id in stop.shapes:
                route = self._network.route_for_shape(shape_id)
                direction = self._network.direction_for_shape(shape_id)
                destination = self._network.destination_for_shape(shape_id)
                shape = self._network.snapshot.shapes.get(shape_id, ())
                # A trip's final stop is an arrival, not a departure towards it.
                positions = [
                    index for index, entry in enumerate(shape[:-1]) if entry.stop_id == stop.stop_id
                ]
                if route is None or direction is None or destination is None or not positions:
                    continue
                for trip in timetable.trips.get(shape_id, ()):
                    if trip.service_id not in active:
                        continue
                    for index in positions:
                        day_offset, minute = divmod(
                            trip.start_minute + trip.offsets[index], _MINUTES_PER_DAY
                        )
                        departure_at = datetime.combine(
                            day + timedelta(days=day_offset),
                            time_type(minute // 60, minute % 60),
                            tzinfo=self._zone,
                        )
                        key = (route.line, direction, departure_at)
                        if key in seen:
                            continue
                        seen.add(key)
                        departures.append(
                            ScheduleDeparture(
                                line=route.line,
                                destination=destination,
                                direction=direction,
                                mode=route.mode,
                                shape_id=shape_id,
                                departure_at=departure_at,
                            )
                        )

        departures.sort(key=lambda departure: (departure.departure_at, departure.line))
        expired = service_date > timetable.end
        warnings: tuple[str, ...] = ()
        if expired:
            warnings = (
                f"The bundled timetable ended on {timetable.end.isoformat()}; only "
                "after-midnight trips of its last service day are included.",
            )
        elif service_date == timetable.end:
            warnings = (
                f"The bundled timetable ends on {timetable.end.isoformat()}; departures "
                "after that service day are not included.",
            )
        return ProviderResult(
            value=tuple(departures),
            fetched_at=timetable.generated_at.astimezone(UTC),
            warnings=warnings,
            complete=not expired,
        )
